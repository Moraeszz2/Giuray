# Builds dist/qt_themes/giuray/style.qss: the theme's own rules (base.qss), the sizing rules the
# controller and input screens need (taken from the qdarkstyle theme, its colors turned into the
# Giuray palette), and overrides.qss last. Run again after editing base.qss or overrides.qss.
$ErrorActionPreference = 'Stop'
$themes = [IO.Path]::GetFullPath("$PSScriptRoot/../dist/qt_themes")
$base = Get-Content -Raw "$themes/giuray/base.qss"
$overrides = Get-Content -Raw "$themes/giuray/overrides.qss"
$dark = Get-Content "$themes/qdarkstyle/style.qss"

# The per-widget rules start at the input settings' refresh button and run to the end.
$start = [Array]::FindIndex($dark, [Predicate[string]] { param($l) $l -like 'QPushButton#buttonRefreshDevices*' })
if ($start -lt 0) { throw 'qdarkstyle: per-widget rules not found' }
$tail = ($dark[$start..($dark.Length - 1)] -join "`n")

$colors = [ordered]@{
    '#232629' = '#1F1F23'; '#31363b' = '#27272A'; '#76797c' = '#3F3F46'; '#54575b' = '#303036'
    '#2a2929' = '#1F1F23'; '#929192' = '#A1A1AA'; '#f0f0f0' = '#E4E4E7'; '#39ff14' = '#DC2626'
}
foreach ($key in $colors.Keys) {
    $tail = [Regex]::Replace($tail, [Regex]::Escape($key), $colors[$key], 'IgnoreCase')
}

$header = "/* Generated by tools/New-GiurayThemeStyle.ps1 from base.qss and qdarkstyle's per-widget rules. */`n`n"
$text = $header + $base.TrimEnd() + "`n`n/* ---------- Controller and input screens (sizes from qdarkstyle) ---------- */`n`n" + $tail.TrimEnd() + "`n`n" + $overrides.TrimEnd() + "`n"
[IO.File]::WriteAllText("$themes/giuray/style.qss", $text, (New-Object Text.UTF8Encoding($false)))
Write-Host "Wrote $themes/giuray/style.qss"
